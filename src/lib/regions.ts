export type ScAccount = "EU" | "US";

// Which SC account ships to a given country. When both accounts can serve a
// destination (the common case), EU is preferred because its shipping is
// cheaper from a Frankfurt-based store. Returns null if neither account
// covers the destination.
export function accountFor(iso: string, active: readonly ScAccount[]): ScAccount | null {
  if (active.includes("EU") && EU_DELIVERABLE_ISO.includes(iso)) return "EU";
  if (active.includes("US") && US_DELIVERABLE_ISO.includes(iso)) return "US";
  return null;
}

// The set of countries to advertise in Stripe Checkout: union of every
// active account's deliverable list. A customer in a US-only destination
// reaches checkout, picks their country, and the webhook later routes to
// the US account when fulfilling.
export function allowedCountries(active: readonly ScAccount[]): string[] {
  const set = new Set<string>();
  if (active.includes("EU")) for (const c of EU_DELIVERABLE_ISO) set.add(c);
  if (active.includes("US")) for (const c of US_DELIVERABLE_ISO) set.add(c);
  return [...set].sort();
}

// Parse SC_ACTIVE_ACCOUNTS env var ("EU" or "EU,US") into the runtime set.
// Defaults to ["EU"] — only the EU account is wired up today.
export function activeAccountsFromEnv(): ScAccount[] {
  const raw = process.env.SC_ACTIVE_ACCOUNTS;
  if (!raw) return ["EU"];
  const parts = raw
    .split(",")
    .map((s) => s.trim().toUpperCase())
    .filter((s): s is ScAccount => s === "EU" || s === "US");
  return parts.length ? parts : ["EU"];
}
